const DICTS: Record<Lang, Record<string, string>> = { de: DE, en: EN };

export function getLang(): Lang {
  try {
    const s = localStorage.getItem(STORE_KEY);
    if (s === "de" || s === "en") return s;
  } catch {
    /* ignore */
  }
  return navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}

export function setLang(l: Lang): void {
  try {
    localStorage.setItem(STORE_KEY, l);
  } catch {
    /* ignore */
  }
  location.reload();
}

const _lang = getLang();

export function t(key: string): string {
  return DICTS[_lang][key] ?? DE[key] ?? key;
}

/** <select> für die globale Sprachauswahl. */
export function langSelect(): string {
  return `<select id="globalLang" title="Sprache / Language">
    <option value="de" ${_lang === "de" ? "selected" : ""}>DE</option>
    <option value="en" ${_lang === "en" ? "selected" : ""}>EN</option>
  </select>`;
}

export function wireLangSelect(root: ParentNode): void {
  root.querySelector<HTMLSelectElement>("#globalLang")?.addEventListener("change", (e) => {
    setLang((e.target as HTMLSelectElement).value as Lang);
  });
}
